package dev.shaurmalib.common.camera.replay;

/**
 * Як глядач потрапляє НА початок клипу з попереднього (для першого клипу
 * скрипта не має значення — початок сцени керує споживач).
 */
public enum ReplayTransition {
    /** Жорстка склейка: кадр стрибає на першу точку нового клипу. */
    CUT,
    /** Короткий провал у чорне: затемнення → склейка під чорним → розтемнення. */
    DIP_TO_BLACK
}
