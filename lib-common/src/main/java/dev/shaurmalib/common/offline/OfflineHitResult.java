package dev.shaurmalib.common.offline;

/**
 * Відповідь режиму на удар по тілу (план, §4.6).
 */
public enum OfflineHitResult {
    /** Удар не зараховано: без анімації й без шкоди. */
    IGNORED,
    /** Зараховано: показати анімацію/звук ушкодження, тіло живе. */
    HIT,
    /** Власник «помер» за правилами режиму: запускається вбивство тіла з дропом. */
    KILLED
}
