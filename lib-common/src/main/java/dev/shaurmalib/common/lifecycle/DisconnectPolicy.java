package dev.shaurmalib.common.lifecycle;

/**
 * Політика для гравця, що вийшов і повернувся під час/після матчу (п. 3.8
 * плану: "дати повернення чи інше").
 */
public enum DisconnectPolicy {
    /** Відновити інвентар/позицію/стан матчу так, ніби гравець не виходив. */
    PRESERVE_STATE,
    /** Скинути гравця в режим спостерігача при поверненні. */
    RESET_TO_SPECTATOR,
    /** Гравець вважається таким, що вибув з матчу остаточно. */
    KICK_FROM_MATCH
}
