package dev.shaurmalib.common.lifecycle;

/**
 * Політика для гравця, що приєднався під час активного матчу (п. 3.8 плану:
 * "що робити з гравцями які... зайшли під час активної гри").
 */
public enum JoinPolicy {
    /** Гравець стає спостерігачем поточного матчу. */
    SPECTATE,
    /** Гравець потрапляє в чергу очікування наступного матчу (лобі). */
    QUEUE,
    /** Гравцю відмовлено в приєднанні до сервера/світу матчу. */
    REJECT
}
