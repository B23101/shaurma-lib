package dev.shaurmalib.common.chat;

import java.util.List;
import java.util.UUID;

/**
 * Міст між рушієм чату бібліотеки і рольовою логікою консюмера.
 *
 * <p>Бібліотека не знає нічого про ролі, команди чи режими: вона лише
 * питає консюмера три речі — «у які канали цей гравець має право
 * писати?», «кого досягне повідомлення цього каналу?» і «яким кольором
 * підписати його нік?». Маніяк підставляє сюди свої рольові групи
 * (лобі / виживші / маньяки / глядачі), снайпери — свої команди.</p>
 *
 * <p>Глобальний канал ({@link ChatChannel#GLOBAL_ID}) рушій обробляє сам,
 * не питаючи провайдера: у нього пишуть усі й читають усі.</p>
 */
public interface ChatChannelProvider {

    /**
     * Канали, у які гравець має право писати ЗАРАЗ. Порожній список
     * означає «лише глобальний чат» — це коректний і типовий стан (напр.
     * лобі, де рольових каналів ще немає).
     */
    List<String> writableChannels(UUID sender);

    /**
     * UUID усіх, кого досягне повідомлення каналу {@code channelId}.
     * Якщо тут не буде самого відправника — бібліотека додасть його саму,
     * щоб гравець бачив власне повідомлення.
     */
    List<UUID> recipientsOf(String channelId, UUID sender);

    /**
     * HEX-колір (напр. {@code "#E04A4A"}) для ніку відправника в цьому
     * каналі — саме він фарбує нік у чаті «за групою». {@code null} —
     * бібліотека бере колір каналу.
     */
    default String colorHexOf(String channelId, UUID sender) {
        return null;
    }
}
