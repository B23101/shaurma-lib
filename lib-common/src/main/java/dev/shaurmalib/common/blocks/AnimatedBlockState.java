package dev.shaurmalib.common.blocks;

/**
 * Узагальнений lifecycle-стан анімованого блоку (план, п. 3.27) —
 * узагальнення {@code CaseBlockEntity.AnimState} snipers_shaurma
 * ({@code IDLE, OPENING, OPEN, CLOSING, REFILLING}).
 * <p>
 * Ці п'ять станів покривають увесь спостережений патерн "контейнер, у який
 * можна зазирнути" (кейс) без жодної кейс-специфіки в самій назві — тому
 * переносяться 1:1, а не перейменовуються під нейтральніші терміни:
 * {@code REFILLING} лишається доменним словом навіть для консюмерів, чий
 * блок не є луут-кейсом, бо семантика та сама — "тимчасово недоступний,
 * бо вміст перегенеровується", а вигадування нейтральнішої назви на кшталт
 * {@code RESETTING} нічого не додає й ускладнює порівняння з оригіналом.
 * <p>
 * Консюмер, якому не потрібен якийсь із проміжних станів (наприклад блок
 * без фази рефілу), просто ніколи не переводить {@code AnimatedBlockEntityBase}
 * у {@link #REFILLING} — enum лишається спільним, а не розширюваним per-block,
 * щоб {@code animPredicate}-подібний рушій (план, розширення нижче) міг
 * залишатись одним switch-виразом на всю бібліотеку.
 */
public enum AnimatedBlockState {
    IDLE,
    OPENING,
    OPEN,
    CLOSING,
    REFILLING
}
