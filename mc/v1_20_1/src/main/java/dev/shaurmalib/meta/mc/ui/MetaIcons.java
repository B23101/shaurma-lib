    private static void put(String id, String... rows) { ICONS.put(id, rows); }

    private MetaIcons() {}

    public static boolean has(String id) { return ICONS.containsKey(id); }

    /** @param px розмір одного пікселя іконки (1 → 8×8, 2 → 16×16) */
    public static void draw(GuiGraphics g, String id, int x, int y, int px, int argb) {
        String[] rows = ICONS.getOrDefault(id == null ? "" : id, ICONS.get("star"));
        int dark = MetaUi.mix(argb, 0xFF000000 | (argb & 0xFF000000), .55f);
        dark = (argb & 0xFF000000) | (MetaUi.bright(argb, .55f) & 0xFFFFFF);
        for (int r = 0; r < rows.length; r++) {
            String row = rows[r];
            for (int c = 0; c < row.length(); c++) {
                char ch = row.charAt(c);
                if (ch == '.') continue;
                g.fill(x + c * px, y + r * px, x + (c + 1) * px, y + (r + 1) * px, ch == '+' ? dark : argb);
            }
        }
    }
