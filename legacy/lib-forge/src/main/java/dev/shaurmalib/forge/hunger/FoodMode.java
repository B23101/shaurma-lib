package dev.shaurmalib.forge.hunger;

/**
 * Режим керування голодом гравця (план: "лобі — голод не тратиться").
 * <p>
 * Бібліотека сама НІЧОГО не вирішує про те, коли гравець "у лобі" —
 * це знає лише споживач (головний мод), тому весь модуль зведений до
 * одного простого перемикача на гравця, який споживач сам виставляє
 * у потрібний момент (вхід у лобі / повернення у гру тощо), напр.:
 * <pre>{@code
 * FoodControlService.setMode(player, FoodMode.ALWAYS_FULL); // зайшов у лобі
 * ...
 * FoodControlService.setMode(player, FoodMode.VANILLA);     // почалась гра
 * }</pre>
 */
public enum FoodMode {
    /** Нічого не робимо — голод рахується повністю ванільно, як завжди. */
    VANILLA,

    /**
     * Кожен тік примусово виставляється максимум (20 ситості / 20 saturation).
     * Ванільна витрата (біг, стрибки, регенерація тощо) щотіку відкочується
     * назад — голод у гравця завжди виглядає повним.
     */
    ALWAYS_FULL,

    /**
     * Голод тримається на зафіксованому значенні і НЕ тратиться через
     * ванільні механізми (exhaustion/tick) — але це значення можна в
     * будь-який момент змінити програмно через
     * {@link FoodControlService#setFixedFood(net.minecraft.server.level.ServerPlayer, int, float)}
     * ("становленням"). Після зміни нове значення так само тримається,
     * поки його знову не змінять або не перемкнуть режим.
     */
    FIXED
}
